#define N(a) ((int)(sizeof(a) / sizeof((a)[0])))

static int parse_code(const char *s, uint32_t *bits)
{
    int len = 0;
    uint32_t v = 0;
    for (; *s; s++) {
        if (*s == ' ') continue;
        v = (v << 1) | (uint32_t)(*s == '1');
        len++;
    }
    *bits = v;
    return len;
}

static int fill1(mv_vlc *t, int tbits, const code1 *c, int n)
{
    memset(t, 0, sizeof(mv_vlc) << tbits);
    for (int i = 0; i < n; i++) {
        uint32_t v;
        int len = parse_code(c[i].code, &v);
        if (len < 1 || len > tbits) return -1;
        int sh = tbits - len;
        for (uint32_t j = 0; j < (1u << sh); j++) {
            mv_vlc *e = &t[(v << sh) | j];
            if (e->len) return -1;        /* not prefix-free */
            e->val = (int8_t)c[i].v;
            e->len = (uint8_t)len;
        }
    }
    return 0;
}

static int fill_dct(mv_dct_tab *t, const code2 *c, int n)
{
    memset(t, 0, sizeof(*t));
    for (int i = 0; i < n; i++) {
        uint32_t v;
        int len = parse_code(c[i].code, &v);
        mv_dct_ent ent;
        ent.run = (uint8_t)c[i].run;
        ent.level = (uint8_t)c[i].level;
        ent.len = (uint8_t)len;
        ent.pad = 0;
        if (len < 1 || len > 16) return -1;
        if (len >= 9 && (v >> (len - 8)) == 0) {
            /* 0000 0000 + (len-8) bits: second-level table on bits 9..16 */
            if (len < 13) return -1;
            uint32_t rest = v & ((1u << (len - 8)) - 1);
            int sh = 16 - len;
            for (uint32_t j = 0; j < (1u << sh); j++) {
                mv_dct_ent *e = &t->b[(rest << sh) | j];
                if (e->len) return -1;
                *e = ent;
            }
        } else {
            if (len > 12) return -1;
            int sh = 12 - len;
            for (uint32_t j = 0; j < (1u << sh); j++) {
                mv_dct_ent *e = &t->a[(v << sh) | j];
                if (e->len) return -1;
                *e = ent;
            }
        }
    }
    return 0;
}

int mv_tables_build(mv_tables *t)
{
    if (fill1(t->mba, MV_MBA_BITS, k_mba, N(k_mba))) return -1;
    if (fill1(t->mbt[0], MV_MBT_BITS, k_mbt_i, N(k_mbt_i))) return -1;
    if (fill1(t->mbt[1], MV_MBT_BITS, k_mbt_p, N(k_mbt_p))) return -1;
    if (fill1(t->mbt[2], MV_MBT_BITS, k_mbt_b, N(k_mbt_b))) return -1;
    if (fill1(t->cbp, MV_CBP_BITS, k_cbp, N(k_cbp))) return -1;
    if (fill1(t->mc, MV_MC_BITS, k_mc, N(k_mc))) return -1;
    if (fill1(t->dcl, MV_DCL_BITS, k_dcl, N(k_dcl))) return -1;
    if (fill1(t->dcc, MV_DCC_BITS, k_dcc, N(k_dcc))) return -1;
    if (fill_dct(&t->dct0, k_dct0, N(k_dct0))) return -1;
    if (fill_dct(&t->dct1, k_dct1, N(k_dct1))) return -1;
    return 0;
}

/* Kraft sums: a complete prefix code sums to exactly 1. Known incompleteness:
 * B-1 lacks the MPEG-1 stuffing code and the all-zero start-code prefix; B-9 lacks 0000
 * 0000 0; B-12/B-13 are complete; B-14/B-15 have a few unused 0000 0000 0000 xxxx codes
 * and (B-15) the slots vacated by the reassigned codes. The test checks sums against the
 * values implied by the standard, so a dropped or duplicated row shows up. */
static double kraft1(const code1 *c, int n)
{
    double s = 0;
    for (int i = 0; i < n; i++) {
        uint32_t v;
        s += 1.0 / (double)(1u << parse_code(c[i].code, &v));
    }
    return s;
}
static double kraft2(const code2 *c, int n)
{
    double s = 0;
    for (int i = 0; i < n; i++) {
        uint32_t v;
        int len = parse_code(c[i].code, &v);
        /* sign bit halves nothing: each run/level code stands for 2 codewords of len+1 */
        s += 1.0 / (double)(1u << len);
    }
    return s;
}

int mv_tables_selftest(char *err, size_t cap)
{
    static mv_tables t;
    struct { const char *name; double got, want; } k[] = {
        /* B-1: unused are 0000 0010 xxx, 7 of 0000 0001 xxx, 0000 0000 xxx */
        {"B-1 mba", kraft1(k_mba, N(k_mba)), 1.0 - 7.0 / 2048.0 - 2.0 / 256.0},
        {"B-2 mbt I", kraft1(k_mbt_i, N(k_mbt_i)), 0.75},
        {"B-3 mbt P", kraft1(k_mbt_p, N(k_mbt_p)), 1.0 - 1.0 / 64.0},
        {"B-4 mbt B", kraft1(k_mbt_b, N(k_mbt_b)), 1.0 - 1.0 / 64.0},
        {"B-9 cbp", kraft1(k_cbp, N(k_cbp)), 1.0 - 1.0 / 512.0},
        {"B-12 dc luma", kraft1(k_dcl, N(k_dcl)), 1.0},
        {"B-13 dc chroma", kraft1(k_dcc, N(k_dcc)), 1.0},
        {"B-14 dct0", kraft2(k_dct0, N(k_dct0)), 1.0 - 16.0 / 65536.0},
        {"B-15 dct1", kraft2(k_dct1, N(k_dct1)),
         1.0 - 16.0 / 65536.0 - 6.0 / 4096.0 - 4.0 / 8192.0},
    };
    /* B-10 magnitudes: unused are 0000 0010 xx and 0000 000x xx (12 of 1024) */
    double mc = kraft1(k_mc, N(k_mc));
    for (size_t i = 0; i < sizeof(k) / sizeof(k[0]); i++) {
        double d = k[i].got - k[i].want;
        if (d > 1e-12 || d < -1e-12) {
            if (err) snprintf(err, cap, "%s: Kraft sum %.10f, expected %.10f", k[i].name,
                              k[i].got, k[i].want);
            return -1;
        }
    }
    if (mc - (1.0 - 12.0 / 1024.0) > 1e-12 || mc - (1.0 - 12.0 / 1024.0) < -1e-12) {
        if (err) snprintf(err, cap, "B-10 motion_code: Kraft sum %.10f", mc);
        return -1;
    }
    if (mv_tables_build(&t) != 0) {
        if (err) snprintf(err, cap, "a code list is not prefix-free");
        return -1;
    }
    return 0;
}

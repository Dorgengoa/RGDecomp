/* Emissive surfaces for ray tracing (docs/RAYTRACING.md "RT8", lane rt8 2026-11-02).
 *
 * The PS2 art fakes lamps, screens, crystals, lava and glowing signs with bright or additive
 * textures; nothing lights the surroundings.  This module knows such textures and turns their
 * draws into lights for the ray-traced receivers:
 *
 *   - texture identity by content: emi_key() of the decoded level-0 RGBA texels (w x h), the
 *     same on every run, map visit and VRAM placement (the renderer's own cache key is not:
 *     it names local-memory pages); key text "rgba:%016llx";
 *   - the emissive table (census/emissive.tsv; compiled in from nr_emi_tab.h, generated by
 *     tools/rt/emi_table.py; $RG_EMI_TABLE=path.tsv overrides it at run time): per key emits
 *     yes / no, colour (auto = the emitting texels' mean), strength, mask (all texels, or the
 *     texels with luminance >= N), kind (auto / area / point);
 *   - the census ($RG_EMI_CENSUS=DIR, tools/rt/emi_census.py): every textured draw's class per
 *     texture (additive / blended / plain, immediate / mesh, unlit / vertex-coloured / lit,
 *     vertex brightness, screen area, frames seen) into DIR/census.tsv, and each texture once
 *     as DIR/tex/<key>.png;
 *   - the debug overlay (EMI_OVERLAY): a tagged texture's emitting texels are drawn magenta;
 *   - the frame's emitters (EmiLight): a tagged mesh draw gives one light per cluster of its
 *     emitting triangles (object space, cached per mesh / texture / UV rows), a tagged
 *     immediate draw (glow sprites, halos) one per sprite, unprojected with the frame's camera;
 *   - (rt9) HD packs (docs/TEXTURES.md): a replaced texture is never decoded, so it has no content
 *     key.  Its record comes from rep_tex(): the row keyed by its PCSX2 name ("pcsx2:<name>", key
 *     name_key()), else the row its original's content key has (learned at run time when the
 *     original was decoded and named: bridge), else -- when the pack has <name>_e.png -- an
 *     implied row; the texels that emit and their colour come from the _e map when there is one
 *     (black = none), else from the replacement's own texels under the row's mask.
 *
 * Included by nr_vulkan.cpp only (header-only: no build-file change).  Nothing here runs unless
 * the census, the overlay or emissive lighting is on; nothing reaches game memory. */

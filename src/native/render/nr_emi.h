    static void sample_tex(const Tex &t, float u, float v, bool cu, bool cv, uint32_t &c)
    {
        float x = u * t.w, y = v * t.h;
        int ix = (int)floorf(x), iy = (int)floorf(y);
        ix = cu ? std::min(std::max(ix, 0), t.w - 1) : ((ix % t.w) + t.w) % t.w;
        iy = cv ? std::min(std::max(iy, 0), t.h - 1) : ((iy % t.h) + t.h) % t.h;
        c = t.px[(size_t)iy * t.w + ix];
    }
    /* the emitting clusters of a mesh draw in object space (cached by mesh, texture, UV rows,
     * colour rows): emitting triangles (7 UV samples each: corners, mid-edges, centre) grouped
     * on a grid of a quarter of the mesh's largest extent (at least 24 units) */
    const std::vector<Clu> &mesh_clusters(const Tex &t, const float (*cb)[4], uint32_t var, const void *vtx, uint32_t nvtx,
                                          const uint32_t *idx, uint32_t nidx, uint32_t mesh_id, bool cu, bool cv)
    {
        uint64_t k = 1469598103934665603ull;
        auto mix = [&](const void *p, size_t n) { const uint8_t *b = (const uint8_t *)p; for (size_t i = 0; i < n; i++) { k ^= b[i]; k *= 1099511628211ull; } };
        mix(&mesh_id, 4); mix(&t.key, 8); mix(cb[4], 16); mix(cb[6], 16); mix(cb[7], 16); mix(cb[8], 16); mix(&var, 4);
        auto it = clu_cache.find(k);
        if (it != clu_cache.end()) return it->second;
        std::vector<Clu> &out = clu_cache[k];
        if (clu_cache.size() > 20000) clu_cache.clear();
        const uint8_t *v = (const uint8_t *)vtx;
        if (!v || !idx || nvtx == 0 || nidx < 3) return clu_cache[k];
        /* object-space positions, the vertex colour factor, UVs */
        std::vector<float> P((size_t)nvtx * 3), UV((size_t)nvtx * 2), C((size_t)nvtx * 3);
        float lo[3] = { 1e30f, 1e30f, 1e30f }, hi[3] = { -1e30f, -1e30f, -1e30f };
        for (uint32_t i = 0; i < nvtx; i++) {
            const int16_t *q = (const int16_t *)(v + 28 * i);
            for (int j = 0; j < 3; j++) {
                P[3 * i + j] = q[j] / 32768.0f * cb[4][j];
                lo[j] = std::min(lo[j], P[3 * i + j]); hi[j] = std::max(hi[j], P[3 * i + j]);
            }
            const int16_t *uvp = (const int16_t *)(v + 28 * i + 12);
            UV[2 * i] = uvp[0] / 32768.0f * cb[6][0] + ((var & V_SCROLL) ? cb[6][2] : 0.0f);
            UV[2 * i + 1] = uvp[1] / 32768.0f * cb[6][1] + ((var & V_SCROLL) ? cb[6][3] : 0.0f);
            float m[3];
            for (int j = 0; j < 3; j++) {
                float base = (var & V_LIGHT) ? cb[21][j] + 0.7f * cb[17][j] : cb[7][j];
                float vc = (var & V_VCOL) ? v[28 * i + 16 + j] * (256.0f / 32768.0f) : 1.0f;
                m[j] = std::min(base * vc, cb[8][j]);
            }
            for (int j = 0; j < 3; j++) C[3 * i + j] = m[j];
        }
        float ext = std::max(hi[0] - lo[0], std::max(hi[1] - lo[1], hi[2] - lo[2]));
        float cell = std::max(ext * 0.25f, 24.0f);
        struct Acc { double p[3], c[3], area, w; float lo[3], hi[3]; };
        std::unordered_map<uint64_t, Acc> grid;
        static const float bw[7][3] = { { 1, 0, 0 }, { 0, 1, 0 }, { 0, 0, 1 }, { .5f, .5f, 0 }, { 0, .5f, .5f }, { .5f, 0, .5f }, { 1 / 3.f, 1 / 3.f, 1 / 3.f } };
        for (uint32_t f = 0; f + 2 < nidx; f += 3) {
            uint32_t a = idx[f], b = idx[f + 1], c = idx[f + 2];
            if (a >= nvtx || b >= nvtx || c >= nvtx) continue;
            int ne = 0;
            float ec[3] = { 0, 0, 0 };
            for (int s = 0; s < 7; s++) {
                float u = bw[s][0] * UV[2 * a] + bw[s][1] * UV[2 * b] + bw[s][2] * UV[2 * c];
                float w = bw[s][0] * UV[2 * a + 1] + bw[s][1] * UV[2 * b + 1] + bw[s][2] * UV[2 * c + 1];
                uint32_t tc;
                sample_tex(t, u, w, cu, cv, tc);
                if (!t.emits(tc)) continue;
                ne++;
                for (int j = 0; j < 3; j++) {
                    float vc = bw[s][0] * C[3 * a + j] + bw[s][1] * C[3 * b + j] + bw[s][2] * C[3 * c + j];
                    float tx = t.row->col_auto ? (float)((tc >> (8 * j)) & 255u) : t.ecol[j];
                    ec[j] += tx * vc / 128.0f;
                }
            }
            if (!ne) continue;
            float e1[3], e2[3], cr[3], cen[3];
            for (int j = 0; j < 3; j++) {
                e1[j] = P[3 * b + j] - P[3 * a + j]; e2[j] = P[3 * c + j] - P[3 * a + j];
                cen[j] = (P[3 * a + j] + P[3 * b + j] + P[3 * c + j]) / 3.0f;
            }
            cr[0] = e1[1] * e2[2] - e1[2] * e2[1]; cr[1] = e1[2] * e2[0] - e1[0] * e2[2]; cr[2] = e1[0] * e2[1] - e1[1] * e2[0];
            float area = 0.5f * sqrtf(cr[0] * cr[0] + cr[1] * cr[1] + cr[2] * cr[2]) * (float)ne / 7.0f;
            if (!(area > 0.0f)) continue;
            int gx = (int)floorf((cen[0] - lo[0]) / cell), gy = (int)floorf((cen[1] - lo[1]) / cell), gz = (int)floorf((cen[2] - lo[2]) / cell);
            uint64_t gk = ((uint64_t)(uint32_t)gx << 42) ^ ((uint64_t)(uint32_t)gy << 21) ^ (uint64_t)(uint32_t)gz;
            Acc &A = grid[gk];
            if (A.w == 0) { for (int j = 0; j < 3; j++) { A.lo[j] = 1e30f; A.hi[j] = -1e30f; } }
            for (int j = 0; j < 3; j++) {
                A.p[j] += cen[j] * area;
                A.c[j] += ec[j] / ne * area;
                for (uint32_t q : { a, b, c }) { A.lo[j] = std::min(A.lo[j], P[3 * q + j]); A.hi[j] = std::max(A.hi[j], P[3 * q + j]); }
            }
            A.area += area;
            A.w += area;
        }
        for (auto &g : grid) {
            Acc &A = g.second;
            if (!(A.w > 0)) continue;
            Clu c;
            for (int j = 0; j < 3; j++) { c.p[j] = (float)(A.p[j] / A.w); c.c[j] = (float)(A.c[j] / A.w); }
            float dx = A.hi[0] - A.lo[0], dy = A.hi[1] - A.lo[1], dz = A.hi[2] - A.lo[2];
            /* the radius of a disc of the emitting area (texels that emit x triangle area), at most the
             * cluster's half extent and 48 units: a large surface whose texels emit here and there is a
             * small light, not a sun */
            (void)dx; (void)dy; (void)dz;
            c.r = std::min(std::min(sqrtf((float)A.area / 3.14159265f), 0.5f * sqrtf(dx * dx + dy * dy + dz * dz)), 48.0f);
            c.r = std::max(c.r, 2.0f);
            c.area = (float)A.area;
            out.push_back(c);
        }
        n_mesh_clu += out.size();
        return out;
    }
    /* light from colour c (0..255 x strength) of an emitter of radius r: its reach (where the
     * r^2 / d^2 falloff of the brightest channel drops under one level) */
    static float reach(const float c[3], float r)
    {
        float m = std::max(c[0], std::max(c[1], c[2]));
        return std::min(r * sqrtf(std::max(m, 1.0f)), 1000.0f);
    }
    bool make_light(const float p[3], float r, const float c[3], Light &L)
    {
        memcpy(L.p, p, sizeof L.p);
        L.r = r;
        memcpy(L.c, c, sizeof L.c);
        L.imp = 0;
        if (std::max(c[0], std::max(c[1], c[2])) < min_c) { n_dropped++; return false; }
        L.range = reach(c, r);
        return true;
    }
    /* static emitters (mesh clusters) stay lit after the game stops drawing them (culled off
     * screen) for $RG_EMI_KEEP game frames (default 90), keyed by mesh, rows, texture, cluster */
    struct Sticky { Light L; uint32_t frame; };
    std::unordered_map<uint64_t, Sticky> sticky;
    std::vector<Light> out_lights;
    int keep = -1;
    /* the lights of the frame just drawn (cur = its record frame): sprites + the sticky set,
     * importance to the camera cam; the per-frame collections restart */
    std::vector<Light> &frame_lights(uint32_t cur, const float cam[3])
    {
        if (keep < 0) { const char *e = getenv("RG_EMI_KEEP"); keep = e && *e ? atoi(e) : 90; }
        out_lights.swap(lights);
        lights.clear();
        seen.clear();
        for (auto it = sticky.begin(); it != sticky.end();) {
            if ((int32_t)(cur - it->second.frame) > keep) { it = sticky.erase(it); continue; }
            out_lights.push_back(it->second.L);
            ++it;
        }
        for (Light &L : out_lights) {
            float dx = L.p[0] - cam[0], dy = L.p[1] - cam[1], dz = L.p[2] - cam[2];
            float d = sqrtf(dx * dx + dy * dy + dz * dz);
            L.imp = (L.c[0] + L.c[1] + L.c[2]) * L.range / (d + L.range);
        }
        return out_lights;
    }
    /* a tagged mesh draw: its clusters to world space (object rows rt[0..3]) as lights */
    void mesh_draw(const Tex &t, const float (*cb)[4], const float (*rt)[4], uint32_t var, const void *vtx, uint32_t nvtx, const uint32_t *idx,
                   uint32_t nidx, uint32_t mesh_id, bool cu, bool cv, uint32_t lframe)
    {
        if (!mode || !t.row || (var & (V_SKIN | V_ZSCALE)) || t.px.empty()) return;
        uint64_t k = 1469598103934665603ull;
        const uint8_t *b = (const uint8_t *)rt;
        for (size_t i = 0; i < 64; i++) { k ^= b[i]; k *= 1099511628211ull; }
        k ^= mesh_id; k *= 1099511628211ull; k ^= t.key;
        if (std::find(seen.begin(), seen.end(), k) != seen.end()) return;
        seen.push_back(k);
        n_draw_tagged++;
        const std::vector<Clu> &cl = mesh_clusters(t, cb, var, vtx, nvtx, idx, nidx, mesh_id, cu, cv);
        const float s = t.row->str * gstr;
        uint64_t ci = 0;
        for (const Clu &c : cl) {
            float p[3], col[3];
            ci++;
            for (int j = 0; j < 3; j++) p[j] = rt[0][j] * c.p[0] + rt[1][j] * c.p[1] + rt[2][j] * c.p[2] + rt[3][j];
            /* the object rows may scale: the radius by the largest column */
            float sc = 0;
            for (int j = 0; j < 3; j++) sc = std::max(sc, sqrtf(rt[j][0] * rt[j][0] + rt[j][1] * rt[j][1] + rt[j][2] * rt[j][2]));
            for (int j = 0; j < 3; j++) col[j] = c.c[j] * s;
            Light L;
            if (make_light(p, std::min(c.r * sc * meshr, 64.0f), col, L)) sticky[(k ^ (ci * 0x9E3779B97F4A7C15ull)) * 1099511628211ull] = Sticky{ L, lframe };
        }
    }
    /* a tagged immediate draw (sprites: triangle pairs): one light per primitive group of up to 2
     * triangles sharing an edge, at its unprojected centre.  w2s: the frame's world -> GS screen
     * (homogeneous, columns); xy: the primitive coordinates (before XYOFFSET); z as the GS holds it */
    bool unproject(const float w2s[4][4], float x, float y, float z, float out[3]) const
    {
        /* rows r_k = (w2s[0][k], w2s[1][k], w2s[2][k], w2s[3][k]); r0.P = x r3.P etc. */
        double A[3][3], B[3];
        const float s[3] = { x, y, z };
        for (int k = 0; k < 3; k++) {
            for (int j = 0; j < 3; j++) A[k][j] = (double)w2s[j][k] - s[k] * (double)w2s[j][3];
            B[k] = s[k] * (double)w2s[3][3] - (double)w2s[3][k];
        }
        double det = A[0][0] * (A[1][1] * A[2][2] - A[1][2] * A[2][1]) - A[0][1] * (A[1][0] * A[2][2] - A[1][2] * A[2][0]) +
                     A[0][2] * (A[1][0] * A[2][1] - A[1][1] * A[2][0]);
        if (!(fabs(det) > 1e-18)) return false;
        double X[3];
        for (int c = 0; c < 3; c++) {
            double M[3][3];
            memcpy(M, A, sizeof M);
            for (int r = 0; r < 3; r++) M[r][c] = B[r];
            X[c] = (M[0][0] * (M[1][1] * M[2][2] - M[1][2] * M[2][1]) - M[0][1] * (M[1][0] * M[2][2] - M[1][2] * M[2][0]) +
                    M[0][2] * (M[1][0] * M[2][1] - M[1][1] * M[2][0])) / det;
        }
        for (int c = 0; c < 3; c++) out[c] = (float)X[c];
        return std::isfinite(out[0]) && std::isfinite(out[1]) && std::isfinite(out[2]);
    }
    /* imv: GpuImVtx (x, y, z, rgba, s, t, q, fog: 8 words each), a triangle list; sprites are
     * taken as consecutive triangle pairs */
    void im_draw(const Tex &t, const uint32_t *imv, uint32_t nv, const float w2s[4][4], float alpha_scale)
    {
        if (!mode || !t.row || nv < 3) return;
        n_draw_tagged++;
        const float s = t.row->str * gstr;
        for (uint32_t i = 0; i + 2 < nv;) {
            uint32_t n = (i + 5 < nv) ? 6 : 3;
            float x0 = 1e30f, x1 = -1e30f, y0 = 1e30f, y1 = -1e30f;
            double z = 0, rgb[3] = { 0, 0, 0 }, a = 0;
            for (uint32_t k = 0; k < n; k++) {
                const uint32_t *q = imv + 8 * (i + k);
                float x, y;
                memcpy(&x, &q[0], 4); memcpy(&y, &q[1], 4);
                x0 = std::min(x0, x); x1 = std::max(x1, x); y0 = std::min(y0, y); y1 = std::max(y1, y);
                z += (double)q[2];
                for (int j = 0; j < 3; j++) rgb[j] += (q[3] >> (8 * j)) & 255u;
                a += q[3] >> 24;
            }
            i += n;
            z /= n; a /= n;
            float c[3], p[3], pe[3];
            if (!unproject(w2s, 0.5f * (x0 + x1), 0.5f * (y0 + y1), (float)z, p)) continue;
            if (!unproject(w2s, x1, 0.5f * (y0 + y1), (float)z, pe)) continue;
            float r = sqrtf((pe[0] - p[0]) * (pe[0] - p[0]) + (pe[1] - p[1]) * (pe[1] - p[1]) + (pe[2] - p[2]) * (pe[2] - p[2]));
            if (!(r > 0.1f) || r > 2000.0f) continue;
            /* additive glows: the colour x alpha / 128; the share of the sprite that emits */
            for (int j = 0; j < 3; j++) c[j] = t.ecol[j] * (float)(rgb[j] / n) / 128.0f * (float)(a / 128.0) * alpha_scale * t.efrac * s;
            Light L;
            /* (a glow sprite's halo is several times its flame / bulb: a third of its half size) */
            if (make_light(p, r * spr, c, L)) { lights.push_back(L); n_im_lights++; }
        }
    }

"""Generate regions_symbols.cfg from symbols.spec.

  python tools/trace/gen_regions.py [--src game/src]

'auto' sizes = distance from the symbol to the next D_00xxxxxx address that
any decomp source references (the decomp's own data-symbol boundaries),
capped at 0x1000. Each symbol becomes one region named sym:<Name>, so a trace
divergence names the variable.
"""
import argparse
import bisect
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
PORT = os.path.dirname(os.path.dirname(HERE))
AUTO_CAP = 0x1000


def referenced_data_symbols(src):
    rx = re.compile(rb"D_00([0-9A-Fa-f]{6})")
    found = set()
    for root, _, files in os.walk(src):
        for f in files:
            if f.endswith((".c", ".cpp", ".h", ".s", ".inc")):
                with open(os.path.join(root, f), "rb") as fh:
                    found.update(int(m, 16) for m in rx.findall(fh.read()))
    return sorted(found)


def parse_spec(path):
    out = []
    with open(path, encoding="utf-8") as f:
        for ln, line in enumerate(f, 1):
            s = line.split("#", 1)[0].strip()
            if not s:
                continue
            parts = s.split(None, 3)
            if len(parts) < 3:
                raise SystemExit("%s:%d: need name address size" % (path, ln))
            out.append((parts[0], parts[1], parts[2], parts[3] if len(parts) > 3 else ""))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", default=os.path.join(HERE, "symbols.spec"))
    ap.add_argument("--src", default=os.path.join(PORT, "game", "src"))
    ap.add_argument("--out", default=os.path.join(HERE, "regions_symbols.cfg"))
    args = ap.parse_args()
    syms = referenced_data_symbols(args.src)
    lines = ["# GENERATED by gen_regions.py from symbols.spec -- edit the spec, not this.",
             "# %d D_ symbols referenced under %s were used for 'auto' sizes." % (len(syms), args.src)]
    for name, addr, size, ev in parse_spec(args.spec):
        if addr.startswith("*"):
            if size == "auto":
                raise SystemExit("%s: deref regions need an explicit size" % name)
            lines.append("ee  sym:%-18s %-18s %s    # %s" % (name, addr, size, ev))
            continue
        a = int(addr, 0)
        if size == "auto":
            i = bisect.bisect_right(syms, a)
            nxt = syms[i] if i < len(syms) else a + 4
            n = min(nxt - a, AUTO_CAP)
        else:
            n = int(size, 0)
        lines.append("ee  sym:%-18s 0x%08X  0x%08X    # size 0x%X; %s" % (name, a, a + n, n, ev))
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", args.out, len(lines) - 2, "regions")


if __name__ == "__main__":
    main()

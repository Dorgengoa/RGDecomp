"""Check the game-save boot fixtures: the broad smoke test (docs/TEST-FIXTURES.md
"Manufactured saves", "Card library").

    python tools/fixtures/bootcheck.py [NAME ...] [--lib | --all] [--exe EXE] [--shots DIR]
                                       [--states] [--tsv FILE] [--keep-logs DIR]

For each boot fixture (fxlib.BOOT_FIXTURES: save2, factory, insectron, save2_battle2 and the
card library cardlib.LIBRARY) one power-on run with the fixture's card and boot script
(run_from.py --boot-save; library cards use boot_lib.input.txt) to its last milestone + 50,
with RG_STATUS_EVERY=50.  A milestone passes when the STATUS line at its field (or any line
in its (first, last) range) shows the expected overlay (loader index) and game mode ("7/*" =
any phase); "optional" milestones are reported but never fail.  A fault prints the
symbolized EXCEPTION and stack (fxlib.crash_report).  Default names: the original fixtures;
--lib = the card library, --all = both.  --shots DIR writes a screenshot per milestone;
--fight (library cards) also fights the first battle of the box walk with autobattle.py
(verdict reported; only a crash / hang fails).  --states writes a save state per milestone into the exe's fixture set (out/fixtures/<exe-id>/
boot/NAME_MILESTONE.rgstate, with RG_SS=1) for play.py --from / navprobe.py.  --tsv appends one
row per fixture (name, verdict, per-milestone results, crash).  Cards missing:
`saveedit.py make` (manufactured + library) or regen.py (save2).  Exit 1 on any FAIL.  One
rg-game at a time.
"""
from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import fxlib  # noqa: E402


def _first(f):
    return f[0] if isinstance(f, tuple) else f


def _last(f):
    return f[1] if isinstance(f, tuple) else f


def _mode_ok(want, got):
    if want is None:
        return True
    if want.endswith("/*"):
        return got.split("/")[0] == want[:-2]
    return got == want


LOAD = [(1900, "CROSS", "title menu: CONTINUE"), (2150, "CROSS", "MEMORY CARD slot 1"),
        (2350, "CROSS", "FILE 01"), (2450, "CROSS", "Load the data in file 1? -> Yes"),
        (2650, "CROSS", "File 1 loaded.")]
RECAP = list(range(3700, 4601, 100))   # CROSS through the chapter recap (LoadingScreenFrame_3435d0)


def lib_script(control):
    """The card-library boot script.  control None = pass 1 (find the field where control
    starts: CROSS every 100 fields through the recap, which takes CROSS / START once its
    text and the load are done); else pass 2: only the recap presses before `control`
    (so no later CROSS talks to an NPC), then the smoke actions relative to it
    (fxlib.lib_milestones)."""
    L = ["# generated by tools/fixtures/bootcheck.py (card library, docs/TEST-FIXTURES.md)"]
    L += [f"{f} {f + 5} {b}  # {c}" for f, b, c in LOAD]
    for f in RECAP:
        if control is None or f < control:
            L.append(f"{f} {f + 3} CROSS  # chapter recap")
    if control is not None:
        c = control
        # menu first: once the party walks, a random encounter may start any time
        L += [f"{c + 60} {c + 63} TRIANGLE  # main menu (game mode 17)",
              f"{c + 260} {c + 263} CIRCLE  # close",
              "#!stick 1 0", f"#!stick {c + 350} {c + 550} 128 0  # walk camera-forward"]
        dirs = [(0, 128, "left"), (128, 255, "back"), (255, 128, "right"), (128, 0, "forward")]
        f, k = c + 700, 0
        while f < c + 3500:
            x, y, n = dirs[k % 4]
            L.append(f"#!stick {f} {f + 149} {x} {y}  # box walk: {n}")
            f, k = f + 150, k + 1
    return "\n".join(L) + "\n"


def snapshot_exe(exe: Path) -> Path:
    """A private copy of the exe (+ .map) for the whole check, keyed by its content: a
    rebuild or relink of the build dir during a long --all run (another lane's ninja) can no
    longer replace or lock the file under a later card.  Same content -> same exe id, so
    the fixture sets / fight states are shared with the original path."""
    exe = Path(exe).resolve()
    if not exe.exists():
        return exe
    d = fxlib.FIXTURES / "runs" / "bootexe" / fxlib.exe_id(exe)
    dst = d / "rg-game.exe"
    if not dst.exists():
        d.mkdir(parents=True, exist_ok=True)
        tmp = d / f"rg-game.{time.time_ns()}.tmp"
        shutil.copy2(exe, tmp)
        tmp.replace(dst)
    mp = exe.with_suffix(".map")
    if mp.exists() and not (d / "rg-game.map").exists():
        tmp = d / f"rg-game.{time.time_ns()}.map.tmp"
        shutil.copy2(mp, tmp)
        tmp.replace(d / "rg-game.map")
    return dst


def run_status(card, script_text, exe, end, every, extra, env_extra, keep_name, keep):
    """One run_from.py --boot-save run with a generated script; (rc, log, {field: (ovl, mode)})."""
    sd = fxlib.FIXTURES / "runs" / "bootlib"
    sd.mkdir(parents=True, exist_ok=True)
    sp = sd / f"{keep_name}.input.txt"
    sp.write_text(script_text, encoding="utf-8")
    cmd = [sys.executable, str(HERE / "run_from.py"), "--boot-save", card, "--input", str(sp),
           "--exe", str(exe), "--fields", str(end), "--"] + extra
    for attempt in range(2):
        t0 = time.time()
        p = subprocess.run(cmd, env=fxlib.game_env(dict(env_extra, RG_STATUS_EVERY=str(every))),
                           capture_output=True, text=True, errors="replace")
        log = p.stdout + p.stderr
        # An exit within seconds and without one STATUS line never reached the game (the
        # "FAIL at 0 s" flake, BRINGUP.md "User play-test 2" item 4): keep the log, say
        # why, and retry once.
        if p.returncode == 0 or parse_status(log) or time.time() - t0 > 20 or attempt:
            break
        el = sd / f"{keep_name}.early-exit.log"
        el.write_text(" ".join(cmd) + chr(10) + log, encoding="utf-8")
        tail = [ln for ln in log.splitlines() if ln.strip()][-3:]
        print(f"  {card}: early exit {p.returncode} after {time.time() - t0:.1f} s, retrying once "
              f"(log {el}): {' | '.join(tail)}", flush=True)
        time.sleep(3)
    if keep:
        keep.mkdir(parents=True, exist_ok=True)
        (keep / f"{keep_name}.log").write_text(log, encoding="utf-8")
    return p.returncode, log, parse_status(log)


def parse_status(log):
    st = {}
    for ln in log.splitlines():
        m = re.match(r"STATUS field=(\d+) .*?ovl=(-?\d+) .*?gamemode=(\S+)", ln)
        if m:
            st[int(m.group(1))] = (int(m.group(2)), m.group(3))
    return st


def check_lib(name, exe, shots, states, keep=None):
    """Two passes: find the field where control starts, then the smoke script relative to it."""
    t0 = time.time()
    rc, log, st = run_status(name, lib_script(None), exe, 4700, 10, [], {}, name + "_pass1", keep)
    ctl = next((k for k, v in sorted(st.items()) if k >= 3700 and v == (3, "6/100")), None)
    crash = fxlib.crash_report(log, exe)
    if ctl is None or crash:
        last = max(st) if st else 0
        seen = sorted({v[1] for k, v in st.items() if k >= 3700})
        print(f"  {name:16s} control        no field control by 4,700 (modes after 3,700: "
              f"{' '.join(seen) or '-'}; exit {rc})  FAIL")
        for c in crash:
            print(f"    {c}")
        print(f"  {name}: FAIL ({time.time() - t0:.0f} s)", flush=True)
        return False, ["control:FAIL"], crash, last
    ms = fxlib.lib_milestones(ctl)
    end = max(_last(m[1]) for m in ms) + 20
    extra, env = [], {}
    if shots:
        shots.mkdir(parents=True, exist_ok=True)
        for m in ms:
            extra += ["--shot", f"{_first(m[1])}:{shots / f'{name}_{m[0]}.png'}"]
    if states:
        sd = fxlib.fixture_dir(exe) / "boot"
        sd.mkdir(parents=True, exist_ok=True)
        for m in ms:
            if not isinstance(m[1], tuple):
                extra += ["--save-state", f"{m[1]}:{sd / f'{name}_{m[0]}.rgstate'}"]
        env["RG_SS"] = "1"
    rc, log, st = run_status(name, lib_script(ctl), exe, end, 10, extra, env, name, keep)
    print(f"  {name:16s} control at field {ctl} (pass 1)")
    return evaluate(name, ms, st, log, rc, exe, t0)


def evaluate(name, ms, st, log, rc, exe, t0):
    ok = True
    results = []
    for m in ms:
        mname, f, ovl, mode = m[:4]
        optional = len(m) > 4 and m[4] == "optional"
        if isinstance(f, tuple):
            hits = [(k, v) for k, v in sorted(st.items()) if f[0] <= k <= f[1] and v[0] == ovl and _mode_ok(mode, v[1])]
            good = bool(hits)
            got = f"first at {hits[0][0]} ({hits[0][1][1]})" if hits else "never"
            where = f"{f[0]}-{f[1]}"
        else:
            g = st.get(f)
            good = g is not None and g[0] == ovl and _mode_ok(mode, g[1])
            got = ("ovl=%d mode=%s" % g) if g else "nothing (run ended?)"
            where = str(f)
        verdict = "OK" if good else ("no" if optional else "FAIL")
        if not optional:
            ok &= good
        results.append(f"{mname}:{verdict}")
        print(f"  {name:16s} {mname:14s} field {where:>11s}  want ovl={ovl} mode={mode or '*'}  got {got}  "
              f"{verdict}{' (optional)' if optional else ''}")
    crash = fxlib.crash_report(log, exe)
    last = max(st) if st else 0
    if crash or rc != 0:
        ok = False
        print(f"  {name}: rg-game exit {rc} (last STATUS field {last}"
              f"{', ' + ' '.join(map(str, st[last])) if last else ''})")
        for c in crash:
            print(f"    {c}")
    print(f"  {name}: {'PASS' if ok else 'FAIL'} ({time.time() - t0:.0f} s)", flush=True)
    return ok, results, crash, last


def check(name: str, exe: Path, shots: Path | None, states: bool, keep: Path | None = None):
    if fxlib.BOOT_SCRIPT.get(name) == "lib":
        return check_lib(name, exe, shots, states, keep)
    ms = fxlib.BOOT_FIXTURES[name]
    end = max(_last(m[1]) for m in ms) + 50
    extra = []
    if shots:
        shots.mkdir(parents=True, exist_ok=True)
        for m in ms:
            extra += ["--shot", f"{_first(m[1])}:{shots / f'{name}_{m[0]}.png'}"]
    env_ss = {}
    if states:
        sd = fxlib.fixture_dir(exe) / "boot"
        sd.mkdir(parents=True, exist_ok=True)
        for m in ms:
            if not isinstance(m[1], tuple):
                extra += ["--save-state", f"{m[1]}:{sd / f'{name}_{m[0]}.rgstate'}"]
        env_ss["RG_SS"] = "1"
    card = fxlib.BOOT_CARD.get(name, name)
    script = fxlib.PORT / "tools" / "trace" / "goldens" / f"boot_{fxlib.BOOT_SCRIPT.get(name, name)}.input.txt"
    cmd = [sys.executable, str(HERE / "run_from.py"), "--boot-save", card, "--input", str(script),
           "--exe", str(exe), "--fields", str(end), "--"] + extra
    t0 = time.time()
    p = subprocess.run(cmd, env=fxlib.game_env(dict(env_ss, RG_STATUS_EVERY="50")),
                       capture_output=True, text=True, errors="replace")
    log = p.stdout + p.stderr
    if keep:
        keep.mkdir(parents=True, exist_ok=True)
        (keep / f"{name}.log").write_text(log, encoding="utf-8")
    st = parse_status(log)
    return evaluate(name, ms, st, log, p.returncode, exe, t0)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("names", nargs="*")
    ap.add_argument("--lib", action="store_true", help="the card library (cardlib.LIBRARY)")
    ap.add_argument("--all", action="store_true", help="original fixtures + the card library")
    ap.add_argument("--exe")
    ap.add_argument("--shots")
    ap.add_argument("--states", action="store_true")
    ap.add_argument("--tsv", help="append one result row per fixture")
    ap.add_argument("--keep-logs", help="write each run's rg-game log here")
    ap.add_argument("--fight", action="store_true",
                    help="library cards: also fight the box walk's first battle (autobattle.py; "
                    "result won / lost / timeout / stuck / crash / hang / no battle; informational, "
                    "only a crash or hang fails the card)")
    a = ap.parse_args(argv)
    exe = snapshot_exe(fxlib.exe_path(a.exe))
    lib = [n for n in fxlib.BOOT_FIXTURES if fxlib.BOOT_SCRIPT.get(n) == "lib"]
    base = [n for n in fxlib.BOOT_FIXTURES if n not in lib]
    names = a.names or (base + lib if a.all else lib if a.lib else base)
    ok = True
    summary = []
    for n in names:
        if n not in fxlib.BOOT_FIXTURES:
            print(f"  {n}: unknown fixture (fxlib.BOOT_FIXTURES)")
            ok = False
            continue
        if not (fxlib.CARDS / fxlib.BOOT_CARD.get(n, n)).is_dir():
            print(f"  {n}: no card {fxlib.CARDS / fxlib.BOOT_CARD.get(n, n)} (saveedit.py make / regen.py)")
            ok = False
            continue
        good, res, crash, last = check(n, exe, Path(a.shots) if a.shots else None, a.states,
                                       Path(a.keep_logs) if a.keep_logs else None)
        if a.fight and fxlib.BOOT_SCRIPT.get(n) == "lib" and good:
            import autobattle
            t0 = time.time()
            fr = autobattle.fight_card(n, exe, keep=Path(a.keep_logs) if a.keep_logs else None,
                                       shots=bool(a.shots))
            v = fr["verdict"]
            print(f"  {n:16s} fight          {v}  ({fr.get('fields', 0)} fields, killed {fr.get('killed', 0)}"
                  f"/{fr.get('enemies_start', 0)}, heals {fr.get('heals', 0)}, {time.time() - t0:.0f} s)", flush=True)
            for c in fr.get("crash") or []:
                print(f"    {c}")
            res.append(f"fight:{v.split()[0]}")
            if v in ("crash", "hang") or v.startswith("no state"):
                good = False
                crash = crash or fr.get("crash") or [v]
        ok &= good
        summary.append((n, good, res, crash, last))
        if a.tsv:
            with open(a.tsv, "a", encoding="utf-8") as f:
                f.write("\t".join([time.strftime("%Y-%m-%d %H:%M"), fxlib.exe_id(exe), n,
                                   "PASS" if good else "FAIL", " ".join(res), str(last), " | ".join(crash)]) + "\n")
    if len(summary) > 1:
        print(f"\nbootcheck: {sum(1 for s in summary if s[1])}/{len(summary)} PASS")
        for n, good, res, crash, last in summary:
            print(f"  {'PASS' if good else 'FAIL'}  {n:16s} {' '.join(res)}{'  CRASH ' + crash[0] if crash else ''}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())

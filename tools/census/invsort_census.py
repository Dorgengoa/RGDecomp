"""Item-sort category map (docs/SETTINGS.md "Sort items by category", lane invsort 2026-11-09).

Reads the game's own item table (rc/param/item_param_EN, #4 row = id, '', name, def category
(def +0x2), code (+0x4), index (+0x3), owner chara data id (+0x8), mark, +0x6; via
tools/fixtures/rgdata.py) and gives every item a sort rank:

    rank = group * 4 + sub        (lower first; ties: item id, then the item's old slot)

Groups, in order (USER decision 2026-11-09: key items, consumables, shields, character equipment,
non-party equipment, Insectron items, revelation items, materials, factory parts):

     0 key items        def cat 8, 9 (not the Insectron licences), 14, 15, 16, 17, 19
     1 consumables      sub 0 heal (cat 4), 1 boosters / seals (cat 5), 2 pills / food (cat 21)
     2 shields          def cat 3 (owner -1: any member)
     3-10 equipment     one group per character in party order: Jaster, Kisala, Zegram, Simon,
                        Steve, Lilika, Jupis, Deego (def cat 0, 1, 2 with owner = that
                        character); sub 0 = sword (cat 0), 1 = second weapon (cat 1),
                        2 = clothes (cat 2)
    11 other owners     cat 0-2 owned by 11009 / 11010 (not party members)
    12 Insectron items  def cat 6 (Toady), the four licences 16634-16637, 12 (traps / cages),
                        13 (feed), 20 (insects; normally kept in list 7, not in the item grid)
    13 revelation items def cat 10 (the Revelation Flow's own items, Ancient Scrolls ..)
    14 materials        sub 0 materials (cat 11), 1 crystals (cat 7)
    15 factory parts    def cat 18
    16 anything else    (the C side also gives unknown ids this group)

Outputs (both generated; never edit by hand):
    census/invsort_category.tsv   one row per item: id, rank, group, name, def cat, owner
    src/game/rg_invsort_tab.c     the rank table compiled into rg-game (rg_invsort_rank)

    python tools/census/invsort_census.py            # write both
    python tools/census/invsort_census.py --check    # exit 1 when either is stale
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

PORT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PORT / "tools" / "fixtures"))
import rgdata  # noqa: E402

TSV = PORT / "census" / "invsort_category.tsv"
TAB = PORT / "src" / "game" / "rg_invsort_tab.c"

# chara_param_EN data ids, in the USER's party order
PARTY = [(11001, "Jaster"), (11004, "Kisala"), (11008, "Zegram"), (11003, "Simon"),
         (11005, "Steve"), (11006, "Lilika"), (11007, "Jupis"), (11002, "Deego")]
LICENCES = {16634, 16635, 16636, 16637}   # Insectron / Platinum / Gold / Silver License (cat 9)

GROUPS = ["key items", "consumables", "shields"] +          [f"{n} equipment" for _, n in PARTY] +          ["other owners' equipment", "Insectron items", "revelation items", "materials", "factory parts",
          "other"]
G_KEY, G_CONS, G_SHIELD = 0, 1, 2
G_CHARA0 = 3
G_OTHEROWN = G_CHARA0 + len(PARTY)
G_INS, G_REV, G_MAT, G_FAC, G_OTHER = G_OTHEROWN + 1, G_OTHEROWN + 2, G_OTHEROWN + 3,     G_OTHEROWN + 4, G_OTHEROWN + 5


def classify(iid: int, cat: int, owner: int) -> tuple[int, int]:
    """(group, sub) of one item."""
    if cat in (0, 1, 2):
        party = [d for d, _ in PARTY]
        if owner in party:
            return G_CHARA0 + party.index(owner), cat
        return G_OTHEROWN, cat
    if cat == 3:
        return G_SHIELD, 0
    if cat == 10:
        return G_REV, 0
    if cat in (6, 12, 13, 20) or (cat == 9 and iid in LICENCES):
        return G_INS, {6: 0, 9: 0, 12: 1, 13: 2, 20: 3}[cat]
    if cat in (8, 9, 14, 15, 16, 17, 19):
        return G_KEY, 0
    if cat in (4, 5, 21):
        return G_CONS, {4: 0, 5: 1, 21: 2}[cat]
    if cat in (11, 7):
        return G_MAT, {11: 0, 7: 1}[cat]
    if cat == 18:
        return G_FAC, 0
    return G_OTHER, 0


def rows():
    out = []
    for cid, a in rgdata.table("item_param_EN.cfg.bin"):
        if cid != 4:
            continue
        iid, name, cat, owner = a[0], a[2], a[3], a[6]
        g, s = classify(iid, cat, owner)
        out.append((iid, g * 4 + s, g, name, cat, owner))
    out.sort()
    return out


def render(rs):
    tsv = ["# generated by tools/census/invsort_census.py from rc/param/item_param_EN (do not edit)",
           "# id\trank\tgroup\tgroup_name\tname\tdef_cat\towner"]
    for iid, rank, g, name, cat, owner in rs:
        tsv.append(f"{iid}\t{rank}\t{g}\t{GROUPS[g]}\t{name}\t{cat}\t{owner}")
    lo, hi = rs[0][0], rs[-1][0]
    other = G_OTHER * 4
    tab = {iid: rank for iid, rank, *_ in rs}
    vals = [tab.get(i, other) for i in range(lo, hi + 1)]
    c = ["/* SPDX-License-Identifier: CC0-1.0 */",
         "/* GENERATED by tools/census/invsort_census.py from the game's item table",
         " * (rc/param/item_param_EN); census/invsort_category.tsv lists the same ranks with names.",
         " * Do not edit: re-run the script.  docs/SETTINGS.md \"Sort items by category\". */",
         "#include <stdint.h>", "",
         "int rg_invsort_rank(int item_id);", "",
         f"#define RG_INVSORT_LO {lo}", f"#define RG_INVSORT_HI {hi}",
         f"#define RG_INVSORT_OTHER {other}", "",
         "/* rank = group * 4 + sub; groups: " + ", ".join(f"{i} {g}" for i, g in enumerate(GROUPS)) + " */",
         f"static const uint8_t k_rank[{len(vals)}] = {{"]
    for i in range(0, len(vals), 24):
        c.append("    " + ", ".join(str(v) for v in vals[i:i + 24]) + ",")
    c += ["};", "",
          "int rg_invsort_rank(int item_id)",
          "{",
          "    if (item_id < RG_INVSORT_LO || item_id > RG_INVSORT_HI)",
          "        return RG_INVSORT_OTHER;",
          "    return k_rank[item_id - RG_INVSORT_LO];",
          "}", ""]
    return "\n".join(tsv) + "\n", "\n".join(c)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    try:
        rs = rows()
    except (OSError, KeyError, SystemExit) as e:   # no game data (data/DATA0_0) on this machine
        print(f"SKIP: item table not readable ({e})")
        return 77
    tsv, c = render(rs)
    # the TSV lists the game's item names, so the public tree leaves it out (generate it with
    # this script from your own data); --check then checks the compiled table only
    stale = [p for p, t in ((TSV, tsv), (TAB, c))
             if (not p.exists() and not (a.check and p == TSV))
             or (p.exists() and p.read_text(encoding="utf-8") != t)]
    if a.check:
        for p in stale:
            print(f"STALE {p.relative_to(PORT)}")
        return 1 if stale else 0
    for p, t in ((TSV, tsv), (TAB, c)):
        p.write_text(t, encoding="utf-8", newline="\n")
    from collections import Counter
    n = Counter(g for _, _, g, *_ in rs)
    print(f"{len(rs)} items -> {TSV.relative_to(PORT)}, {TAB.relative_to(PORT)}")
    for g, name in enumerate(GROUPS):
        print(f"  {g:2d} {name:28s} {n.get(g, 0)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

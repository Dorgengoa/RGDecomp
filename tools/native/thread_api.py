"""Generate the EE-kernel service API list (docs/NATIVE-THREADS.md "Native kernel table").

    python tools/native/thread_api.py            # rewrite src/native/threads/kapi/ps2k_api.inc
    python tools/native/thread_api.py --check    # exit 1 if the .inc is stale

The ps2k API (src/native/threads/kapi/ps2k.h, ps2k_ss.h) has two implementations:
the EE kernel HLE (src/ps2/kernel, the oracle: RG_THREADS=hle|service|frame) and the
native kernel table (src/native/threads/rg_nk*.c: RG_THREADS=native).  Both compile
their definitions under renamed symbols (kapi/ps2k_rename.h: ps2k_hle_* / rg_nk_*);
the dispatcher (src/ps2/kernel/kdispatch.c, default builds) defines every ps2k_*
from the list this script writes; RG_NATIVE_ONLY builds link the native table
under the real names instead (no dispatcher, no HLE).

Each row: PS2K_API(ret, name, (params), (args)) or PS2K_APIV(name, (params), (args))
for void functions.  The fixed-address fiber arena (ps2k_fiber_*) is not part of it
(one implementation, src/native/threads/fiber).  Rerun after changing a prototype.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KAPI = ROOT / "src/native/threads/kapi"
HEADERS = [KAPI / "ps2k.h", KAPI / "ps2k_ss.h"]
OUT = KAPI / "ps2k_api.inc"
RENAME = KAPI / "ps2k_rename.h"

PROTO = re.compile(r"^\s*([A-Za-z_][\w\s\*]*?)\b(ps2k_\w+)\s*\(([^()]*(?:\([^()]*\)[^()]*)*)\)\s*$", re.S)


def strip_comments(t: str) -> str:
    t = re.sub(r"/\*.*?\*/", " ", t, flags=re.S)
    t = re.sub(r"//[^\n]*", " ", t)
    t = re.sub(r"^\s*#.*$", " ", t, flags=re.M)
    return t


def protos():
    out = []
    seen = set()
    for h in HEADERS:
        t = strip_comments(h.read_text(encoding="utf-8"))
        # typedefs of function pointers are not prototypes
        t = re.sub(r"typedef[^;]*;", ";", t)
        for stmt in re.split(r"[;{}]", t):
            m = PROTO.match(stmt)
            if not m:
                continue
            ret = " ".join(m.group(1).split())
            name = m.group(2)
            params = " ".join(m.group(3).split())
            if name.startswith("ps2k_fiber_") or name in seen or ret in ("", "return"):
                continue
            seen.add(name)
            args = []
            if params not in ("void", ""):
                for p in params.split(","):
                    a = re.findall(r"[A-Za-z_]\w*", p)
                    args.append(a[-1])
            out.append((ret, name, params or "void", args))
    return out


def render(rows) -> tuple[str, str]:
    inc = ["/* SPDX-License-Identifier: CC0-1.0",
           " * GENERATED by tools/native/thread_api.py from kapi/ps2k.h + kapi/ps2k_ss.h: do not edit.",
           " * The ps2k API, one row per function (docs/NATIVE-THREADS.md \"Native kernel table\"). */"]
    ren = ["/* SPDX-License-Identifier: CC0-1.0",
           " * GENERATED by tools/native/thread_api.py: do not edit.",
           " * Include BEFORE ps2k.h with PS2K_RENAME_PREFIX defined (ps2k_hle_ / rg_nk_): every ps2k",
           " * API function is then declared and defined under that prefix (the two implementations",
           " * of the API coexist in a default build; kdispatch.c defines the real names). */",
           "#ifndef PS2K_RENAME_H", "#define PS2K_RENAME_H",
           "#define PS2K_RENAME_CAT2(a, b) a##b",
           "#define PS2K_RENAME_CAT(a, b) PS2K_RENAME_CAT2(a, b)",
           "#define PS2K_RENAMED(n) PS2K_RENAME_CAT(PS2K_RENAME_PREFIX, n)"]
    for ret, name, params, args in rows:
        short = name[len("ps2k_"):]
        a = "(" + ", ".join(args) + ")"
        if ret == "void":
            inc.append(f"PS2K_APIV({short}, ({params}), {a})")
        else:
            inc.append(f"PS2K_API({ret}, {short}, ({params}), {a})")
        ren.append(f"#define {name} PS2K_RENAMED({short})")
    ren.append("#endif")
    return "\n".join(inc) + "\n", "\n".join(ren) + "\n"


def main(argv):
    rows = protos()
    inc, ren = render(rows)
    if "--check" in argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == inc and \
            RENAME.exists() and RENAME.read_text(encoding="utf-8") == ren
        print(f"thread_api: {len(rows)} functions; {'up to date' if ok else 'STALE: rerun tools/native/thread_api.py'}")
        return 0 if ok else 1
    OUT.write_text(inc, encoding="utf-8", newline="\n")
    RENAME.write_text(ren, encoding="utf-8", newline="\n")
    print(f"thread_api: {len(rows)} functions -> {OUT.relative_to(ROOT)}, {RENAME.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

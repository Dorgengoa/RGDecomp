"""Generate rg-game's fatal stubs for the classified unbound symbols.

    python tools/gen_unbound.py missing/UNBOUND.tsv OUT.c

Each `fn` row becomes `void SYM(void)` that prints
`rg-game: UNBOUND <sym> (<class>) called` once and aborts (PLAN P1: a stub hit
is a finding).  Each `data` row becomes a zero-filled 64-byte, 16-aligned
block.  docs/LINK.md "Unbound symbols".  Written only when the bytes change.
"""
from __future__ import annotations

import sys
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    rows = []
    for ln in Path(sys.argv[1]).read_text(encoding="utf-8").splitlines():
        if not ln.strip() or ln.startswith("#"):
            continue
        f = ln.split("\t")
        rows.append((f[0], f[1], f[2] if len(f) > 2 else "-"))
    out = ["/* GENERATED by tools/gen_unbound.py from missing/UNBOUND.tsv -- do not edit. */",
           "#include <stdio.h>",
           "#include <stdlib.h>",
           "",
           "static void rg_game_unbound(const char *sym, const char *cls)",
           "{",
           "    fprintf(stderr, \"rg-game: UNBOUND %s (%s) called\\n\", sym, cls);",
           "    fflush(stderr);",
           "    abort();",
           "}",
           ""]
    for sym, kind, cls in rows:
        if kind == "data":
            out.append(f"__attribute__((aligned(16))) unsigned char {sym}[64];")
        else:
            out.append(f"void {sym}(void) {{ rg_game_unbound(\"{sym}\", \"{cls}\"); }}")
    data = ("\n".join(out) + "\n").encode()
    p = Path(sys.argv[2])
    if not p.exists() or p.read_bytes() != data:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    print(f"gen_unbound: {len(rows)} stubs")
    return 0


if __name__ == "__main__":
    sys.exit(main())

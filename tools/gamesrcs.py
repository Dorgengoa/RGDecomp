#!/usr/bin/env python3
"""Write the game/ compile list for CMake (cmake/game.cmake).

    python tools/gamesrcs.py <out.cmake> [--game game] [--overrides overrides]

Reads game/MANIFEST.tsv (kind unit or data, .c/.cpp; kind `excluded` is
skipped unless overrides/ holds its C port) and emits one `set(RG_GAME_SRCS_<image> ...)` per image, so CMake
configure never globs the ~20k-file tree on the slow disk.  A file with a
hand-port under overrides/<same relpath> is replaced by the override
(overrides/README.md; ingest.py --check verifies the recorded hash).
Files under missing/ (game functions the snapshot calls but does not define)
are added until the snapshot defines the same symbol (missing/README.md).
The output is written only when its bytes change.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

PORT = Path(__file__).resolve().parent.parent


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("out", type=Path)
    ap.add_argument("--game", type=Path, default=PORT / "game")
    ap.add_argument("--overrides", type=Path, default=PORT / "overrides")
    ap.add_argument("--missing", type=Path, default=PORT / "missing")
    a = ap.parse_args()
    rows = [ln.split("\t") for ln in
            (a.game / "MANIFEST.tsv").read_text(encoding="utf-8").splitlines()[1:]]
    by: dict[str, list[str]] = {}
    novr = 0
    # overrides/PORT_PROVIDED.tsv: game files a port module provides instead
    # (docs/LINK.md "Providers"); they are not compiled
    provided: set[str] = set()
    pp = a.overrides / "PORT_PROVIDED.tsv"
    if pp.is_file():
        for ln in pp.read_text(encoding="utf-8").splitlines():
            if ln.strip() and not ln.startswith("#"):
                provided.add(ln.split("\t")[0])
    nprov = 0
    for r in rows:
        rel, image, kind = r[0], r[2], r[3]
        ovr = a.overrides / rel
        # an `excluded` (asm-bodied) file is compiled only through its C port
        # in overrides/ (docs/BINDINGS.md)
        if kind == "excluded" and ovr.is_file():
            kind = "unit"
        if kind not in ("unit", "data") or not rel.endswith((".c", ".cpp")):
            continue
        if rel in provided:
            nprov += 1
            continue
        if ovr.is_file():
            path = ovr.resolve().as_posix()
            novr += 1
        else:
            path = (a.game / rel).resolve().as_posix()
        by.setdefault(image, []).append(path)
    # missing/<relpath>: game functions the snapshot calls but does not define
    # (missing/README.md).  Compiled into the image of their directory until
    # the snapshot itself defines the symbol (file stem, or FUN_<addr>); then
    # the stand-in is skipped with a note, and should be deleted.
    defined: set[str] = set()
    img_of_dir: dict[str, str] = {}
    for r in rows:
        if len(r) > 4:
            defined.update(r[4].split(","))
        img_of_dir.setdefault(r[0].rsplit("/", 1)[0], r[2])
    nmiss = 0
    for f in sorted(a.missing.rglob("*")) if a.missing.is_dir() else []:
        if f.suffix not in (".c", ".cpp"):
            continue
        rel = f.relative_to(a.missing).as_posix()
        stem = f.stem
        addr = stem.rsplit("_", 1)[-1]
        if stem in defined or f"FUN_{addr.zfill(8)}" in defined or rel in {r[0] for r in rows}:
            print(f"gamesrcs: missing/{rel} is now defined by the snapshot; skipped (delete it)")
            continue
        image = img_of_dir.get(rel.rsplit("/", 1)[0], "main")
        by.setdefault(image, []).append(f.resolve().as_posix())
        nmiss += 1
    out = ["# GENERATED by tools/gamesrcs.py from game/MANIFEST.tsv -- do not edit.",
           f"set(RG_GAME_IMAGES {' '.join(sorted(by))})",
           f"set(RG_GAME_OVERRIDES {novr})"]
    for img in sorted(by):
        out.append(f"set(RG_GAME_SRCS_{img}")
        out.extend(f"  \"{p}\"" for p in sorted(by[img]))
        out.append(")")
    data = ("\n".join(out) + "\n").encode()
    if not a.out.exists() or a.out.read_bytes() != data:
        a.out.parent.mkdir(parents=True, exist_ok=True)
        a.out.write_bytes(data)
    print(f"gamesrcs: {sum(map(len, by.values()))} sources "
          f"({', '.join(f'{k}={len(v)}' for k, v in sorted(by.items()))}), "
          f"{novr} overrides, {nmiss} missing/ stand-ins, {nprov} port-provided skipped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
